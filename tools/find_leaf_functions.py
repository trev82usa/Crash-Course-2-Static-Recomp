#!/usr/bin/env python3
"""Finds the true boundaries of functions that ReXGlue reports as "target not in any
function". In this game those are leaf functions with no .pdata entry (vtable thunks,
small getters/setters) that sit in the gap after a .pdata function, plus a few huge
functions that ReXGlue splits. Output is a [functions] TOML fragment.

Usage: find_leaf_functions.py image.bin codegen.log [more logs ...] > cc2_leaf_functions.toml
"""
import bisect
import re
import struct
import sys

B = 0x82000000
PDATA = (0x821F3000, 0x34040)
TEXT_END = 0x82230000 + 0xABEACC


def main(image_path, *log_paths):
    img = open(image_path, "rb").read()
    word = lambda a: struct.unpack(">I", img[a - B:a - B + 4])[0]

    pd = []
    for o in range(PDATA[0] - B, PDATA[0] - B + PDATA[1], 8):
        b, w = struct.unpack(">II", img[o:o + 8])
        if b:
            pd.append((b, ((w >> 8) & 0x3FFFFF) * 4))
    pd.sort()
    starts = [p[0] for p in pd]

    def branch(a):
        """(target or None, is_terminator) for the instruction at a."""
        w = word(a)
        op = w >> 26
        if op == 18:                      # b / bl
            li = w & 0x03FFFFFC
            if li & 0x02000000:
                li -= 0x04000000
            t = li if (w & 2) else a + li
            return (None, False) if (w & 1) else (t, True)
        if op == 16:                      # bc
            bd = w & 0xFFFC
            if bd & 0x8000:
                bd -= 0x10000
            t = bd if (w & 2) else a + bd
            return (None, False) if (w & 1) else (t, ((w >> 21) & 0x14) == 0x14)
        if op == 19 and ((w >> 1) & 0x3FF) in (16, 528) and not (w & 1):   # bclr / bcctr
            return (None, ((w >> 21) & 0x14) == 0x14)
        return (None, False)

    def pieces(gap_start, gap_end):
        """Splits [gap_start, gap_end) into functions by following forward branches."""
        a = gap_start
        while a < gap_end:
            while a < gap_end and word(a) == 0:   # padding
                a += 4
            if a >= gap_end:
                return
            start, reach = a, a
            while a < gap_end:
                t, term = branch(a)
                if t is not None and start <= t < gap_end:
                    reach = max(reach, t)
                a += 4
                if term and a > reach:
                    break
            yield start, a - start

    log = "".join(open(p).read() for p in log_paths)
    # "0xT from 0xS: ... target not in any function"  -> the function containing T
    # "Unresolved conditional branch to 0xT from 0xS"  -> the function containing S
    targets = {int(m, 16) for m in re.findall(r"  0x([0-9A-F]{8}) from 0x[0-9A-F]{8}", log)}
    targets |= {int(m, 16) for m in re.findall(r"Unresolved conditional branch to 0x[0-9A-F]{8} from 0x([0-9A-F]{8})", log)}
    targets = sorted(targets)
    found = {}
    for t in targets:
        i = bisect.bisect_right(starts, t) - 1
        if i >= 0 and pd[i][0] <= t < pd[i][0] + pd[i][1]:
            found[pd[i][0]] = (pd[i][1], f"whole .pdata function (contains 0x{t:08X})")
            continue
        gap_start = pd[i][0] + pd[i][1] if i >= 0 else 0x82230000
        gap_end = starts[i + 1] if i + 1 < len(starts) else TEXT_END
        for s, n in pieces(gap_start, gap_end):
            if s <= t < s + n:
                found[s] = (n, f"leaf without .pdata (contains 0x{t:08X})")
                break
        else:
            print(f"# 0x{t:08X}: no boundary found", file=sys.stderr)

    print("# Generated by tools/find_leaf_functions.py from ReXGlue's unresolved-call errors.")
    print("[functions]")
    for s in sorted(found):
        n, why = found[s]
        print(f"0x{s:08X} = {{ size = 0x{n:X} }}  # {why}")


if __name__ == "__main__":
    main(*sys.argv[1:])
